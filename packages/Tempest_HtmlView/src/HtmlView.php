declare(strict_types=1);

namespace AKl\Tempest_HtmlView;

use Dom\HTMLDocument;
use Tempest\Log\Logger;
use Tempest\Support\Html\HtmlString;
use Tempest\Support\Path\Path;
use Tempest\View\View;
use AKl\Tempest_HtmlView\AssetManager;
use AKl\Tempest_HtmlView\Exception\DomManipulationFailed;

use function Tempest\get;
use function Tempest\Support\Arr\is_empty;
use function Tempest\Support\Arr\sort_keys;
use function Tempest\Support\Filesystem\write_file;
use function Tempest\Support\path;

abstract class HtmlView implements View
{
    private readonly Path $basePath;
    private readonly string $baseName;

    private string $viewDir = 'HtmlViews' . \DIRECTORY_SEPARATOR; // TODO: make this configurable

    public string $path {
        get => $this->viewDir . $this->baseName . '.view.php';
    }

    public string $relativeRootPath {
        // or relative to *.view.php?
        get => $this->basePath->toString();
    }

    /** @var array<int, \Closure(HTMLDocument):HTMLDocument> */
    private(set) array $DomManipulations = [];

    public function __construct()
    {
        $this->setPaths();
        $this->createViewFile($this->basePath->append(DIRECTORY_SEPARATOR, $this->path));
        $this->autoUseAssets();
    }

    abstract public function template(): HtmlContent;

    public function toHtml(): HtmlString
    {
        if (is_empty($this->DomManipulations)) {
            return $this->template()->render();
        }

        $dom = Dom(
            $this->template()->render()->toString(),
        );

        foreach (sort_keys($this->DomManipulations) as $manipulation) {
            try {
                $dom = $manipulation($dom);
            } catch (\Throwable $th) {
                throw new DomManipulationFailed(
                    $th,
                    onFile: $this->path,
                    manipulator: $manipulation,
                );
            }
        }

        return new HtmlString($dom->body->innerHTML ?? '');
    }

    /**
     * Convert the rendered HTML of the component to a \Dom\HTMLDocument.
     *
     * TODO: test it…
